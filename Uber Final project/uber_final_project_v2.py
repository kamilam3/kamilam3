def var_across_city_reliability(df,var):

  avg_var = df.groupby(['city', 'is_reliable_pickup'])[var].mean().unstack()
  avg_var.columns = ['Avg_' +var+ '_Unreliable', 'Avg_' +var+ '_Reliable']

  # Add city-level summary
  avg_var['City_Avg_'+var] = df.groupby('city')[var].mean()

  # Format results
  avg_var = avg_var.round(2)  # Show 2 decimal places
  return avg_var

