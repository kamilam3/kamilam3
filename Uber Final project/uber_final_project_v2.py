def stat_across_city(df, var):
    # Create dictionary for aggregation with dynamic column names
    agg_dict = {
        f'average_{var}': 'mean',
        f'median_{var}': 'median',
        f'min_{var}': 'min',
        f'max_{var}': 'max',
        'count': 'count'
    }

    # Calculate statistics
    stats_df = df.groupby('city')[var].agg(**agg_dict).reset_index()

    # Round numeric columns (excluding count)
    for col in stats_df.columns:
        if col not in ['city', 'count']:
            stats_df[col] = stats_df[col].round(2)

    return stats_df

